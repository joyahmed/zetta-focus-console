/// Verify Lemon Squeezy webhook signature
///
/// Lemon Squeezy signs webhooks with an HMAC-SHA256 signature.
/// This function verifies that signature.
///
/// # Arguments
/// * `payload` - The raw request body as bytes
/// * `signature` - The X-Signature header value
/// * `secret` - Your Lemon Squeezy signing secret
///
/// # Returns
/// * `true` if signature is valid
/// * `false` if signature is invalid
pub fn verify_webhook_signature(payload: &[u8], signature: &str, secret: &str) -> bool {
    use hmac::{Hmac, Mac};
    type HmacSha256 = Hmac<Sha256>;

    // Create HMAC-SHA256 with signing secret
    let mut mac = match HmacSha256::new_from_slice(secret.as_bytes()) {
        Ok(m) => m,
        Err(_) => return false,
    };

    // Update with payload
    mac.update(payload);

    // Get result
    let result = mac.finalize();
    let computed_signature = hex::encode(result.into_bytes());

    // Compare signatures (constant-time comparison would be better)
    computed_signature == signature
}

