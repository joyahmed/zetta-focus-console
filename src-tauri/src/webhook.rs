/// Product tier mapping from Lemon Squeezy variant names
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ProductTier {
    Pro,
    Founder,
}

impl ProductTier {
    /// Parse from Lemon Squeezy variant name
    pub fn from_variant_name(name: &str) -> Option<Self> {
        let name_lower = name.to_lowercase();
        if name_lower.contains("founder") {
            Some(ProductTier::Founder)
        } else if name_lower.contains("pro") {
            Some(ProductTier::Pro)
        } else {
            None
        }
    }

    /// Convert to license tier string
    pub fn to_license_tier(&self) -> &'static str {
        match self {
            ProductTier::Pro => "PRO",
            ProductTier::Founder => "FOUNDER",
        }
    }
}

/// Generate a unique license ID
/// Format: XXXX-XXXX (8 alphanumeric characters)
pub fn generate_license_id() -> String {
    use rand::Rng;
    const CHARSET: &[u8] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789";
    let mut rng = rand::thread_rng();

    let part1: String = (0..4)
        .map(|_| {
            let idx = rng.gen_range(0..CHARSET.len());
            CHARSET[idx] as char
        })
        .collect();

    let part2: String = (0..4)
        .map(|_| {
            let idx = rng.gen_range(0..CHARSET.len());
            CHARSET[idx] as char
        })
        .collect();

    format!("{}-{}", part1, part2)
}

/// License generation result
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct GeneratedLicense {
    /// The full license key (format: ZFC-TIER-CODE.SIGNED_DATA)
    pub license_key: String,
    /// The tier (PRO or FOUNDER)
    pub tier: String,
    /// Customer email
    pub customer_email: String,
    /// License ID
    pub license_id: String,
    /// Whether the license was cryptographically signed
    pub is_signed: bool,
}

/// Process a Lemon Squeezy webhook and generate a license key
///
/// This function:
/// 1. Parses the webhook payload
/// 2. Determines the product tier
/// 3. Generates a signed license key (if signing key available)
/// 4. Returns the license for email delivery
///
/// # Arguments
/// * `payload` - The verified webhook payload
///
/// # Returns
/// * `Some(GeneratedLicense)` if successful
/// * `None` if the webhook doesn't require license generation
pub fn process_webhook(payload: &WebhookPayload) -> Option<GeneratedLicense> {
    // Only process order_paid events
    if payload.event != "order_paid" && payload.event != "order_created" {
        return None;
    }

    // Check order status
    let status = payload.data.attributes.status.as_ref()?;
    if status != "paid" {
        return None;
    }

    // Get customer info
    let customer_email = payload.data.attributes.user_email.as_ref()?.clone();
    let _customer_name = payload.data.attributes.user_name.as_ref();

    // Determine product tier
    let variant_name = payload.data.attributes.variant_name.as_ref()?;
    let tier = ProductTier::from_variant_name(variant_name)?;

    // Generate license ID
    let license_id = generate_license_id();

    // Generate the license key with optional signing
    let (license_key, is_signed) = generate_signed_license_key(&tier, &license_id);

    Some(GeneratedLicense {
        license_key,
        tier: tier.to_license_tier().to_string(),
        customer_email,
        license_id,
        is_signed,
    })
}

/// Generate a signed license key
///
/// This function creates a license key in the format:
/// `ZFC-TIER-CODE.SIGNED_DATA`
///
/// Where SIGNED_DATA contains the base64-encoded signed license payload.
///
/// # Arguments
/// * `tier` - The product tier (Pro or Founder)
/// * `license_id` - The unique license identifier (XXXX-XXXX format)
///
/// # Returns
/// A tuple of (license_key, is_signed) where is_signed indicates whether
/// the key was cryptographically signed
fn generate_signed_license_key(tier: &ProductTier, license_id: &str) -> (String, bool) {
    // Generate the base key format
    let base_key = format!("ZFC-{}-{}", tier.to_license_tier(), license_id);

    // In production with signing feature enabled, sign the license
    #[cfg(feature = "signing")]
    {
        use crate::license_crypto::SignedLicense;
        use std::sync::LazyLock;
        use ed25519_dalek::SigningKey;

        // Create the license payload
        let payload = LicensePayload::new(tier.to_license_tier().to_string(), license_id.to_string());

        // The signing key would be loaded from secure storage
        // This is a placeholder - in production, load from environment or secure storage
        static SIGNING_KEY: LazyLock<Option<SigningKey>> = LazyLock::new(|| {
            // TODO: Load actual signing key from secure storage
            // For now, return None to use unsigned keys
            None
        });

        if let Some(signing_key) = SIGNING_KEY.as_ref() {
            let signed = SignedLicense::sign(payload, signing_key);
            let encoded = signed.encode();
            return (format!("{}.{}", base_key, encoded), true);
        }
    }

    // Without signing feature or signing key, return unsigned key
    (base_key, false)
}

