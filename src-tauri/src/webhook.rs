// ============================================================================

/// Response to send back to Lemon Squeezy
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct WebhookResponse {
    /// Success status
    pub success: bool,
    /// Message
    pub message: String,
    /// License key (only included in development mode)
    #[serde(skip_serializing_if = "Option::is_none")]
    pub license_key: Option<String>,
}

impl WebhookResponse {
    /// Create a success response
    pub fn success(message: &str) -> Self {
        Self {
            success: true,
            message: message.to_string(),
            license_key: None,
        }
    }

    /// Create an error response
    pub fn error(message: &str) -> Self {
        Self {
            success: false,
            message: message.to_string(),
            license_key: None,
        }
    }

    /// Add license key to response (for development)
    pub fn with_license_key(mut self, key: &str) -> Self {
        self.license_key = Some(key.to_string());
        self
    }
}

