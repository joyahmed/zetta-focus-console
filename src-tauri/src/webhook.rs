#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_product_tier_from_variant() {
        assert_eq!(ProductTier::from_variant_name("Pro License"), Some(ProductTier::Pro));
        assert_eq!(ProductTier::from_variant_name("Founder Edition"), Some(ProductTier::Founder));
        assert_eq!(ProductTier::from_variant_name("PRO"), Some(ProductTier::Pro));
        assert_eq!(ProductTier::from_variant_name("FOUNDER"), Some(ProductTier::Founder));
        assert_eq!(ProductTier::from_variant_name("Unknown"), None);
    }

    #[test]
    fn test_generate_license_id() {
        let id = generate_license_id();
        assert_eq!(id.len(), 9); // XXXX-XXXX
        assert!(id.contains('-'));
    }

    #[test]
    fn test_webhook_response() {
        let success = WebhookResponse::success("License generated");
        assert!(success.success);

        let error = WebhookResponse::error("Invalid signature");
        assert!(!error.success);
    }

    #[test]
    fn test_process_webhook() {
        let payload = WebhookPayload {
            event: "order_paid".to_string(),
            data: WebhookData {
                id: "test-123".to_string(),
                attributes: WebhookAttributes {
                    status: Some("paid".to_string()),
                    user_email: Some("test@example.com".to_string()),
                    user_name: Some("Test User".to_string()),
                    product_name: Some("Zetta Focus Console".to_string()),
                    variant_name: Some("Pro License".to_string()),
                    total: Some(29.0),
                    currency: Some("USD".to_string()),
                    license_key: None,
                },
            },
            timestamp: Some("2024-01-01T00:00:00Z".to_string()),
        };

        let result = process_webhook(&payload);
        assert!(result.is_some());

        let license = result.unwrap();
        assert_eq!(license.tier, "PRO");
        assert_eq!(license.customer_email, "test@example.com");
        assert!(license.license_key.starts_with("ZFC-PRO-"));
        // Without signing feature, is_signed should be false
        assert!(!license.is_signed);
    }

    #[test]
    fn test_generate_signed_license_key() {
        let tier = ProductTier::Pro;
        let license_id = "ABCD-1234";

        let (key, is_signed) = generate_signed_license_key(&tier, license_id);

        // Key should start with ZFC-PRO-
        assert!(key.starts_with("ZFC-PRO-ABCD-1234"));

        // Without signing feature, is_signed should be false
        assert!(!is_signed);
    }

    #[test]
    fn test_founder_license_generation() {
        let payload = WebhookPayload {
            event: "order_paid".to_string(),
            data: WebhookData {
                id: "test-456".to_string(),
                attributes: WebhookAttributes {
                    status: Some("paid".to_string()),
                    user_email: Some("founder@example.com".to_string()),
                    user_name: Some("Founder User".to_string()),
                    product_name: Some("Zetta Focus Console".to_string()),
                    variant_name: Some("Founder Edition".to_string()),
                    total: Some(19.0),
                    currency: Some("USD".to_string()),
                    license_key: None,
                },
            },
            timestamp: Some("2024-01-01T00:00:00Z".to_string()),
        };

        let result = process_webhook(&payload);
        assert!(result.is_some());

        let license = result.unwrap();
        assert_eq!(license.tier, "FOUNDER");
        assert!(license.license_key.starts_with("ZFC-FOUNDER-"));
    }
}
