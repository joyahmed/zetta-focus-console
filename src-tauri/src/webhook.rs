//! Lemon Squeezy Webhook Handler Module
//!
//! This module handles webhook events from Lemon Squeezy payment provider.
//! When a purchase is completed, Lemon Squeezy sends a webhook that triggers
//! license key generation and delivery.
//!
//! ## Webhook Flow
//! 1. User completes payment on Lemon Squeezy
//! 2. Lemon Squeezy sends webhook to our backend
//! 3. Backend validates webhook signature
//! 4. Backend generates signed license key using Ed25519
//! 5. Backend sends license key to user via email
//!
//! ## Security
//! - Webhook signatures are verified using Lemon Squeezy's signing secret (HMAC-SHA256)
//! - License keys are signed with our private key (Ed25519)
//! - Sensitive data is never logged
//!
//! ## Integration Architecture
//! ```text
//! Lemon Squeezy → Webhook → Backend (this module) → Generate Signed Key → Email User
//! ```
//!
//! The licensing engine remains fully controlled by Rust:
//! - Lemon Squeezy: Payment processing, VAT/tax, order confirmation, license delivery
//! - Rust: License verification, signature validation, feature gating, offline enforcement

use serde::{Deserialize, Serialize};
use sha2::Sha256;

